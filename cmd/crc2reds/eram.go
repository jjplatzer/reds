func convertEramCursors(inPath, outPath string) error {
	paths, err := eramCursorInputFiles(inPath)
	if err != nil {
		return err
	}
	if len(paths) == 0 {
		return fmt.Errorf("no ERAM .cur or .cur.zst files found in %s", inPath)
	}

	cursors := make([]cursorBitmap, 0, len(paths))
	seen := make(map[string]bool, len(paths))

	for _, path := range paths {
		cursor, err := decodeCursorFile(path)
		if err != nil {
			return err
		}
		if seen[cursor.name] {
			return fmt.Errorf("duplicate ERAM cursor name after sanitizing: %s", cursor.name)
		}
		seen[cursor.name] = true
		cursors = append(cursors, cursor)
	}

	sort.Slice(cursors, func(i, j int) bool {
		return eramCursorSortKey(cursors[i].name) < eramCursorSortKey(cursors[j].name)
	})

	if err := writeEramCursorGo(outPath, cursors); err != nil {
		return err
	}

	fmt.Printf("wrote %s\n", outPath)
	fmt.Print("converted ERAM cursors:")
	for _, cursor := range cursors {
		fmt.Printf(" %s(%dx%d hot=%d,%d)", cursor.name, cursor.width, cursor.height, cursor.hotspot[0], cursor.hotspot[1])
	}
	fmt.Println()

	return nil
}

func eramCursorInputFiles(inPath string) ([]string, error) {
	info, err := os.Stat(inPath)
	if err != nil {
		return nil, err
	}

	if !info.IsDir() {
		if !isCursorInputFile(filepath.Base(inPath)) {
			return nil, fmt.Errorf("-in must be an ERAM .cur/.cur.zst file or CRC's Cursors directory: %s", inPath)
		}
		return []string{inPath}, nil
	}

	entries, err := os.ReadDir(inPath)
	if err != nil {
		return nil, err
	}

	byName := make(map[string]string)
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}

		name := entry.Name()
		if strings.HasPrefix(name, "._") || !isCursorInputFile(name) {
			continue
		}

		cursorName := cursorNameFromPath(name)
		if !eramWantedCursorNames[cursorName] {
			continue
		}

		byName[cursorName] = filepath.Join(inPath, name)
	}

	paths := make([]string, 0, len(byName))
	missing := make([]string, 0)
	for _, name := range eramWantedCursorOrder {
		path, ok := byName[name]
		if !ok {
			missing = append(missing, name+".cur")
			continue
		}
		paths = append(paths, path)
	}

	if len(paths) == 0 {
		return nil, nil
	}
	if len(missing) > 0 {
		return nil, fmt.Errorf("ERAM cursor directory %s is missing expected CRC cursor files: %s", inPath, strings.Join(missing, ", "))
	}

	return paths, nil
}

func eramCursorSortKey(name string) int {
	for i, wanted := range eramWantedCursorOrder {
		if name == wanted {
			return i
		}
	}
	return len(eramWantedCursorOrder)
}

func writeEramCursorGo(outPath string, cursors []cursorBitmap) error {
	if err := os.MkdirAll(filepath.Dir(outPath), 0o755); err != nil {
		return err
	}

	var b strings.Builder
	b.WriteString("// Code generated by cmd/crc2reds; DO NOT EDIT.\n")
	b.WriteString("// Source: ERAM .cur(.zst) files converted to exact RGBA cursor pixels.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", eramAssetPackage)
	fmt.Fprintf(&b, "import renderer %q\n\n", eramRendererImport)

	fmt.Fprintf(&b, "var %s = map[string]*renderer.CursorBitmap{\n", eramCursorVarName)

	for _, cursor := range cursors {
		fmt.Fprintf(&b, "\t%q: {\n", cursor.name)
		fmt.Fprintf(&b, "\t\tName:    %q,\n", cursor.name)
		fmt.Fprintf(&b, "\t\tWidth:   %d,\n", cursor.width)
		fmt.Fprintf(&b, "\t\tHeight:  %d,\n", cursor.height)
		fmt.Fprintf(&b, "\t\tHotspot: [2]int{%d, %d},\n", cursor.hotspot[0], cursor.hotspot[1])
		fmt.Fprintf(&b, "\t\tPixels:  %s,\n", formatUint32Array(cursor.pixels, "\t\t"))
		b.WriteString("\t},\n\n")
	}

	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "func %s(name string) (*renderer.CursorBitmap, bool) {\n", eramCursorFuncName)
	fmt.Fprintf(&b, "\tc, ok := %s[name]\n", eramCursorVarName)
	b.WriteString("\treturn c, ok\n")
	b.WriteString("}\n")

	return os.WriteFile(outPath, []byte(b.String()), 0o644)
}
